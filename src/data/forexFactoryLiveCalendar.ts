/**
 * Converts authentic Forex Factory items to typed EconomicEvent array with real timestamps and status
 */
export function getAuthenticForexFactoryEvents(): EconomicEvent[] {
  const now = Date.now();

  return AUTHENTIC_FOREX_FACTORY_ITEMS.map((item) => {
    const timestamp = new Date(item.isoString).getTime();
    const isPast = (item.actual !== null && item.actual !== undefined && timestamp < now) || (timestamp < now - 5 * 60 * 1000);
    const isImminent = !isPast && (timestamp - now < 30 * 60 * 1000 && timestamp > now);
    const status: EconomicEvent['status'] = isPast ? 'RELEASED' : isImminent ? 'IMMINENT' : 'UPCOMING';

    return {
      id: item.id,
      code: item.code,
      title: item.title,
      country: item.country,
      currency: item.currency,
      flag: item.flag,
      datetime: new Date(timestamp).toISOString(),
      dateUtc: new Date(timestamp).toISOString(),
      timestamp,
      period: item.period,
      importance: item.importance,
      status,
      actual: item.actual ?? null,
      forecast: item.forecast,
      previous: item.previous,
      unit: item.unit,
      metrics: {
        headlineForecast: item.forecast || 0,
        headlinePrevious: item.previous || 0,
        headlineActual: item.actual,
      },
      description: item.description,
    };
  });
}

/**
 * Converts raw Forex Factory items to ForexFactoryRawEvent array
 */
export function getAuthenticForexFactoryRawEvents(): ForexFactoryRawEvent[] {
  return AUTHENTIC_FOREX_FACTORY_ITEMS.map((item) => ({
    date: item.dateStr,
    time: item.timeStr,
    currency: item.currency,
    event: item.title,
    impact: item.importance === 'HIGH' ? 'High' : item.importance === 'MEDIUM' ? 'Medium' : 'Low',
    forecast: item.forecast !== null ? `${item.forecast}${item.unit}` : null,
    previous: item.previous !== null ? `${item.previous}${item.unit}` : null,
    actual: item.actual !== null && item.actual !== undefined ? `${item.actual}${item.unit}` : null,
  }));
}
