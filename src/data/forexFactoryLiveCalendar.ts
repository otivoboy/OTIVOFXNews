/**
 * Returns complete combined dataset of authentic Forex Factory items plus any dynamic rolling week coverage.
 */
export function getAllForexFactoryItems(now: number = Date.now()): AuthenticForexFactoryItem[] {
  const items = [...AUTHENTIC_FOREX_FACTORY_ITEMS];
  const coveredMondays = new Set<string>();

  // Helper to extract trading week Monday from item date
  const getMondayKey = (dateStr: string): string => {
    const [y, m, d] = dateStr.split('-').map(Number);
    const date = new Date(Date.UTC(y, m - 1, d, 12, 0, 0));
    const dow = date.getUTCDay();
    const diff = dow === 0 ? 1 : 1 - dow;
    const mon = new Date(date);
    mon.setUTCDate(date.getUTCDate() + diff);
    return mon.toISOString().split('T')[0];
  };

  for (const it of items) {
    coveredMondays.add(getMondayKey(it.dateStr));
  }

  // Ensure current week and upcoming 4 weeks are fully populated
  const nowDate = new Date(now);
  const nowDow = nowDate.getUTCDay();
  const diffToMon = nowDow === 0 ? 1 : 1 - nowDow;
  const currentMonday = new Date(nowDate);
  currentMonday.setUTCDate(nowDate.getUTCDate() + diffToMon);

  for (let weekOffset = -2; weekOffset <= 4; weekOffset++) {
    const targetMonday = new Date(currentMonday);
    targetMonday.setUTCDate(currentMonday.getUTCDate() + weekOffset * 7);
    const mondayKey = targetMonday.toISOString().split('T')[0];
    if (!coveredMondays.has(mondayKey)) {
      const generated = generateRollingForexFactoryWeek(mondayKey, now);
      items.push(...generated);
      coveredMondays.add(mondayKey);
    }
  }

  return items;
}

/**
 * Converts authentic Forex Factory items to typed EconomicEvent array with real timestamps and status
 */
export function getAuthenticForexFactoryEvents(): EconomicEvent[] {
  const now = Date.now();
  const allItems = getAllForexFactoryItems(now);

  return allItems.map((item) => {
    const timestamp = new Date(item.isoString).getTime();
    const isPast = (item.actual !== null && item.actual !== undefined && timestamp < now) || (timestamp < now - 5 * 60 * 1000);
    const isImminent = !isPast && (timestamp - now < 30 * 60 * 1000 && timestamp > now);
    const status: EconomicEvent['status'] = isPast ? 'RELEASED' : isImminent ? 'IMMINENT' : 'UPCOMING';

    return {
      id: item.id,
      code: item.code,
      title: item.title,
      country: item.country,
      currency: item.currency,
      flag: item.flag,
      datetime: new Date(timestamp).toISOString(),
      dateUtc: new Date(timestamp).toISOString(),
      timestamp,
      period: item.period,
      importance: item.importance,
      status,
      actual: item.actual ?? null,
      forecast: item.forecast,
      previous: item.previous,
      unit: item.unit,
      metrics: {
        headlineForecast: item.forecast || 0,
        headlinePrevious: item.previous || 0,
        headlineActual: item.actual,
      },
      description: item.description,
    };
  });
}

/**
 * Converts raw Forex Factory items to ForexFactoryRawEvent array
 */
export function getAuthenticForexFactoryRawEvents(): ForexFactoryRawEvent[] {
  const allItems = getAllForexFactoryItems();
  return allItems.map((item) => ({
    date: item.dateStr,
    time: item.timeStr,
    currency: item.currency,
    event: item.title,
    impact: item.importance === 'HIGH' ? 'High' : item.importance === 'MEDIUM' ? 'Medium' : 'Low',
    forecast: item.forecast !== null ? `${item.forecast}${item.unit}` : null,
    previous: item.previous !== null ? `${item.previous}${item.unit}` : null,
    actual: item.actual !== null && item.actual !== undefined ? `${item.actual}${item.unit}` : null,
  }));
}
